    // Builds RGBA8 texture (with white RGB, glyph coverage in R/A) for compatibility with R8 or RGBA8 upload
    static std::vector<uint8_t> buildAtlasRGBA8() {
        std::vector<uint8_t> pixels(static_cast<size_t>(kAtlasW) * kAtlasH * 4, 0);
        for (int code = 32; code <= 126; ++code) {
            const int idx = code - 32;
            const int cellX = (idx % kCols) * kCellW;
            const int cellY = (idx / kCols) * kCellH;
            const auto& cols = glyph5x7(static_cast<char>(code));
            for (int c = 0; c < 5; ++c) {
                for (int r = 0; r < 7; ++r) {
                    if ((cols[c] >> r) & 1u) {
                        const int px = cellX + c + 1;
                        const int py = cellY + r;
                        const size_t off = (static_cast<size_t>(py) * kAtlasW + px) * 4;
                        pixels[off + 0] = 255;
                        pixels[off + 1] = 255;
                        pixels[off + 2] = 255;
                        pixels[off + 3] = 255;
                    }
                }
            }
        }
        return pixels;
    }
